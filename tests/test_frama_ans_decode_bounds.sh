set -eu
repo_root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd -P)
frama_c=${FRAMA_C:-frama-c}
version=$("$frama_c" -version) || exit "$?"
case "$version" in
    '29.0'*) ;;
    *) printf 'ERROR: this Eva result gate requires Frama-C 29.0, got %s\n' "$version" >&2; exit 1 ;;
esac
log=$(mktemp "${TMPDIR:-/tmp}/zupt-frama-bounds.XXXXXXXX")
trap 'rm -f -- "$log"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

# Keep the actual production match-copy path. Raw literal fixtures do not
# call Huffman; its unused translation unit is outside this analysis scope.
# Frama-C 29 needs the equivalent GCC spelling of C11 _Alignof for parsing.
cpp_args="-I\"$repo_root/include\" -DVV_DISABLE_SIMD=1 -D_Alignof=__alignof__"
if "$frama_c" -machdep gcc_x86_64 -cpp-extra-args="$cpp_args" \
    -warn-invalid-pointer -eva -eva-msg-key=-final-states \
    -eva-slevel 5000 -eva-plevel 4096 \
    -eva-split-return-function vva_decode_sequences_impl:full,vva_decode_sequences:full,vva_decode_sequences_v2:full -main main \
    "$repo_root/src/vv_ans.c" "$repo_root/tests/test_ans_decode_bounds.c" \
    >"$log" 2>&1; then
    cat "$log"
else
    status=$?
    cat "$log"
    exit "$status"
fi

# These builtins occur after successful assertions, so an allocation-failure
# return or a pruned decode cannot stand in for the six reached fixture paths.
# Preserve every diagnostic; only final table-value dumps are disabled above.
diagnostic_status=0
grep -Eiq '(^|[[:space:]])(warning:|error:|failure:|timeout|timed out)' "$log" || diagnostic_status=$?
if [ "$diagnostic_status" -ne 1 ] ||
   ! awk '
    BEGIN {
        expected[1] = "Frama_C_show_each_metadata: {-2}, {18446744073709551615}"
        expected[2] = "Frama_C_show_each_literal_tail: {4}, {68}"
        expected[3] = "Frama_C_show_each_match_tail: {0}, {16}, {20}, {68}"
        expected[4] = "Frama_C_show_each_match_tail: {1}, {16}, {19}, {67}"
        expected[5] = "Frama_C_show_each_match_tail: {0}, {8}, {12}, {68}"
        expected[6] = "Frama_C_show_each_match_tail: {1}, {8}, {11}, {67}"
    }
    {
        marker = index($0, "Frama_C_show_each_")
        if (marker) {
            prefix = substr($0, 1, marker - 1)
            if (prefix ~ /^[[:space:]]*$/) {
                if (!previous_location) bad = 1
            } else if (prefix !~ /^\[eva\] .+:[0-9]+: $/) bad = 1
            witnesses++
            if (summaries || witnesses > 6 || substr($0, marker) != expected[witnesses]) bad = 1
            previous_location = 0
            next
        }
        previous_location = ($0 ~ /^\[eva\] .+:[0-9]+:[[:space:]]*$/)
    }
    /<bottom>|NON TERMINATING FUNCTION/ { bad = 1 }
    /using specification for function (vva_|check_match_tail|build_dec_direct|read_hdr_v2|ans_br_|ll_decode|of_decode)/ { bad = 1 }
    /Some errors and warnings have been raised during the analysis/ { bad = 1 }
    /^[[:space:]]*by (the Eva analyzer|the Frama-C kernel):/ {
        if ($0 !~ /^[[:space:]]*by (the Eva analyzer|the Frama-C kernel):[[:space:]]+0 errors[[:space:]]+0 warnings[[:space:]]*$/) bad = 1
    }
    /^\[eva:summary\]/ {
        summaries++
        if (witnesses != 6 || $0 != "[eva:summary] ====== ANALYSIS SUMMARY ======") bad = 1
    }
    /No errors or warnings raised during the analysis\./ {
        clean++
        if (summaries != 1 || $0 !~ /^[[:space:]]*No errors or warnings raised during the analysis\.[[:space:]]*$/) bad = 1
    }
    /alarms generated by the analysis/ {
        alarms++
        if (summaries != 1 || $0 !~ /^[[:space:]]*0 alarms generated by the analysis\.[[:space:]]*$/) bad = 1
    }
    /statements reached \(out of/ {
        coverage++
        if (summaries != 1 || $0 !~ /^[[:space:]]*In these functions, 558 statements reached \(out of 983\): 56% coverage\.[[:space:]]*$/) bad = 1
    }
    /functions analyzed \(out of/ {
        functions++
        if (summaries != 1 || $0 !~ /^[[:space:]]*16 functions analyzed \(out of 95\): 16% coverage\.[[:space:]]*$/) bad = 1
    }
    /^[[:space:]]*Assertions([[:space:]]|$)/ {
        assertions++
        if (summaries != 1 || $0 !~ /^[[:space:]]*Assertions[[:space:]]+0 valid[[:space:]]+0 unknown[[:space:]]+0 invalid[[:space:]]+0 total[[:space:]]*$/) bad = 1
    }
    /^[[:space:]]*Preconditions([[:space:]]|$)/ {
        preconditions++
        if (summaries != 1 || $0 !~ /^[[:space:]]*Preconditions[[:space:]]+63 valid[[:space:]]+0 unknown[[:space:]]+0 invalid[[:space:]]+63 total[[:space:]]*$/) bad = 1
    }
    END {
        exit !(bad == 0 && witnesses == 6 && summaries == 1 && clean == 1 &&
               alarms == 1 && functions == 1 && coverage == 1 &&
               assertions == 1 && preconditions == 1)
    }
   ' "$log"; then
    printf 'FAIL: ANS bounds analysis is incomplete, pruned or differs from the clean production-scalar fixture result\n' >&2
    exit 1
fi
printf 'PASS: Frama-C ANS bounds metadata and exact tails (production scalar scope)\n'
