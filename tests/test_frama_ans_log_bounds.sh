set -eu
repo_root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd -P)
frama_c=${FRAMA_C:-frama-c}
version=$("$frama_c" -version)
case "$version" in
    '29.0'*) ;;
    *) printf 'ERROR: logarithm Eva gate requires Frama-C 29.0, got %s\n' "$version" >&2; exit 1 ;;
esac
test_log=$(mktemp "${TMPDIR:-/tmp}/zupt-log-eva.XXXXXXXX")
trap 'rm -f -- "$test_log"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
cpp_args="-I\"$repo_root/include\" -DVV_DISABLE_SIMD=1 -DVV_ANS_STANDALONE -D_Alignof=__alignof__"
if "$frama_c" -machdep gcc_x86_64 -cpp-extra-args="$cpp_args" \
    -eva -eva-slevel 16 -eva-slevel-function ilog2:64 -eva-plevel 512 \
    -warn-signed-overflow -warn-unsigned-overflow -main main \
    "$repo_root/tests/test_ans_log_bounds.c" >"$test_log" 2>&1; then
    cat "$test_log"
else
    status=$?
    cat "$test_log"
    exit "$status"
fi
scan_status=0
grep -Ei '(^|[[:space:]])(warning:|error:|failure:|timeout|timed out)' "$test_log" || scan_status=$?
if [ "$scan_status" -ne 1 ]; then
    printf 'FAIL: logarithm analysis diagnostic or scanner failure\n' >&2
    exit 1
fi
# Check returning, reached bodies and a unique complete profile. Zero alarms
# alone cannot establish range assertions or exclude a pruned entry point.
if ! awk '
function require(key, actual, expected) {
    count[key]++
    if (actual != expected) bad = 1
}
{
    line = $0
    sub(/^[[:space:]]+/, "", line)
    sub(/[[:space:]]+$/, "", line)
    gsub(/[[:space:]]+/, " ", line)
    if (line ~ /^\[eva:final-states\] Values at end of function /) {
        block = ""
        if (line == "[eva:final-states] Values at end of function ilog2:") {
            block = "helper"; count["helper"]++
        } else if (line == "[eva:final-states] Values at end of function main:") {
            block = "entry"; count["entry"]++
        } else bad = 1
        next
    }
    if (line ~ /^\[/) block = ""
    if (line ~ /using specification for function (ilog2|main)([^[:alnum:]_]|$)/ ||
        line ~ /<bottom>|NON TERMINATING FUNCTION/) bad = 1
    if (block == "helper") {
        if (line ~ /^v ∈ /) require("v", line, "v ∈ {0}")
        if (line ~ /^r ∈ /) require("r", line, "r ∈ [0..31]")
    }
    if (block == "entry") {
        if (line ~ /^input ∈ /) require("input", line, "input ∈ [--..--]")
        if (line ~ /^bits ∈ /) require("bits", line, "bits ∈ [0..31]")
        if (line ~ /^frequency ∈ /) require("frequency", line, "frequency ∈ [0..4096]")
        if (line ~ /^frequency_bits ∈ /) require("frequency_bits", line, "frequency_bits ∈ [0..12]")
        if (line ~ /^__retres ∈ /) require("return", line, "__retres ∈ {0}")
    }
    if (line ~ /^\[eva:summary\]/)
        require("summary", line, "[eva:summary] ====== ANALYSIS SUMMARY ======")
    if (line ~ /functions analyzed/)
        require("functions", line, "2 functions analyzed (out of 75): 2% coverage.")
    if (line ~ /statements reached/)
        require("coverage", line, "In these functions, 15 statements reached (out of 15): 100% coverage.")
    if (line ~ /errors or warnings raised/)
        require("clean", line, "No errors or warnings raised during the analysis.")
    if (line ~ /alarms generated/)
        require("alarms", line, "0 alarms generated by the analysis.")
    if (line ~ /^Assertions /)
        require("assertions", line, "Assertions 2 valid 0 unknown 0 invalid 2 total")
    if (line ~ /^Preconditions /)
        require("preconditions", line, "Preconditions 2 valid 0 unknown 0 invalid 2 total")
}
END {
    split("helper entry v r input bits frequency frequency_bits return summary functions coverage clean alarms assertions preconditions", keys, " ")
    for (i in keys) if (count[keys[i]] != 1) bad = 1
    exit bad ? 1 : 0
}' "$test_log"; then
    printf 'FAIL: incomplete, mismatched or unproved logarithm analysis\n' >&2
    exit 1
fi
printf 'PASS: Frama-C ANS logarithm ranges (limited scope)\n'
