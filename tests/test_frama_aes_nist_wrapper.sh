# Supervisor controls only; these canned diagnostics do not analyze AES.
set -eu

case "${0##*/}" in
    gcc-aes-fixture)
        if [ "${FRAMA_AES_CASE:-}" = gcc-version ]; then
            printf '16.2.0\n'
        else
            printf '14.3.0\n'
        fi
        exit 0 ;;
    awk) exit 2 ;;
    timeout-aes-fixture)
        # Check argument plumbing only. This mock deliberately enforces no deadline.
        [ "$1" = -s ] && [ "$2" = TERM ] && [ "$3" = -k ] &&
            [ "$4" = 5 ] && [ "$5" = 120 ] || exit 25
        if [ "$FRAMA_AES_CASE" = supervisor-error ]; then exit 24; fi
        shift 5
        exec "$@" ;;
    frama-aes-fixture)
        if [ "${1:-}" = -version ]; then
            if [ "$FRAMA_AES_CASE" = version ]; then
                printf '28.0 (Nickel)\n'
            else
                printf '29.0 (Copper)\n'
            fi
            exit 0
        fi
        case "$FRAMA_AES_CASE" in
            incomplete) printf '[eva] Analysis started\n'; exit 0 ;;
            warning) printf '[kernel] Warning: synthetic parse diagnostic\n' ;;
            external-warning) printf '/tmp/preprocessed.c:1:9: warning: synthetic preprocessor diagnostic\n' ;;
            external-error) printf '/tmp/preprocessed.c:1:9: error: synthetic preprocessor diagnostic\n' ;;
            uppercase-warning) printf '[kernel] WARNING: synthetic parse diagnostic\n' ;;
            uppercase-error) printf '/tmp/preprocessed.c:1:9: ERROR: synthetic preprocessor diagnostic\n' ;;
            mixed-warning) printf '[kernel] wArNiNg: synthetic parse diagnostic\n' ;;
            mixed-error) printf '/tmp/preprocessed.c:1:9: eRrOr: synthetic preprocessor diagnostic\n' ;;
        esac
        printf '[eva] computing for function zupt_aes256_init <- main.\n'
        printf '[eva] computing for function zupt_aes256_encrypt_block <- main.\n'
        printf '[eva] computing for function gmul <- zupt_aes256_encrypt_block <- main.\n'
        if [ "$FRAMA_AES_CASE" != missing-body ]; then
            printf '[eva] computing for function xtime <- gmul <- zupt_aes256_encrypt_block <- main.\n'
        fi
        if [ "$FRAMA_AES_CASE" = spec-body ]; then
            printf '[eva] using specification for function zupt_aes256_encrypt_block\n'
        fi
        byte_count=64
        if [ "$FRAMA_AES_CASE" = byte-count ]; then byte_count=63; fi
        byte=0
        while [ "$byte" -lt "$byte_count" ]; do
            printf '[eva] computing for function __FC_assert <- main.\n'
            byte=$((byte + 1))
        done
        if [ "$FRAMA_AES_CASE" = wrong-oracle ]; then
            printf "  function __FC_assert: precondition 'nonnull_c' got status invalid.\n"
        else
            printf "  function __FC_assert: precondition 'nonnull_c' got status valid.\n"
        fi
        printf '[eva:final-states] Values at end of function main:\n'
        if [ "$FRAMA_AES_CASE" = wrong-oracle ]; then
            printf '  NON TERMINATING FUNCTION\n'
        else
            printf '  __retres ∈ {0}\n'
        fi
        printf '[eva:summary] ====== ANALYSIS SUMMARY ======\n'
        if [ "$FRAMA_AES_CASE" = duplicate ]; then
            printf '[eva:summary] ====== ANALYSIS SUMMARY ======\n'
        fi
        case "$FRAMA_AES_CASE" in
            coverage) printf '  In these functions, 156 statements reached (out of 162): 96%% coverage.\n' ;;
            old-coverage) printf '  In these functions, 160 statements reached (out of 160): 100%% coverage.\n' ;;
            *) printf '  In these functions, 162 statements reached (out of 162): 100%% coverage.\n' ;;
        esac
        printf '  No errors or warnings raised during the analysis.\n'
        if [ "$FRAMA_AES_CASE" = alarm ]; then
            printf '  1 alarms generated by the analysis.\n'
        else
            printf '  0 alarms generated by the analysis.\n'
        fi
        case "$FRAMA_AES_CASE" in
            assertions) printf '  Assertions 0 valid 0 unknown 0 invalid 0 total\n' ;;
            old-assertions) printf '  Assertions 4 valid 0 unknown 0 invalid 4 total\n' ;;
            old-initialization-assertions) printf '  Assertions 6 valid 0 unknown 0 invalid 6 total\n' ;;
            old-helper-assertions) printf '  Assertions 7 valid 0 unknown 0 invalid 7 total\n' ;;
            *) printf '  Assertions 21 valid 0 unknown 0 invalid 21 total\n' ;;
        esac
        case "$FRAMA_AES_CASE" in
            unknown) printf '  Preconditions 6 valid 1 unknown 0 invalid 7 total\n' ;;
            invalid|wrong-oracle) printf '  Preconditions 6 valid 0 unknown 1 invalid 7 total\n' ;;
            *) printf '  Preconditions 7 valid 0 unknown 0 invalid 7 total\n' ;;
        esac
        printf '  100%% of the logical properties reached have been proven.\n'
        case "$FRAMA_AES_CASE" in
            status) exit 23 ;;
            timeout) exit 124 ;;
        esac
        exit 0 ;;
esac

repo_root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd -P)
self="$repo_root/tests/test_frama_aes_nist_wrapper.sh"
test_tmp=$(mktemp -d "${TMPDIR:-/tmp}/zupt-frama-aes-wrapper.XXXXXXXX")
trap 'rm -rf -- "$test_tmp"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
ln -s "$self" "$test_tmp/frama-aes-fixture"
ln -s "$self" "$test_tmp/gcc-aes-fixture"
ln -s "$self" "$test_tmp/timeout-aes-fixture"
mkdir "$test_tmp/awk-failure"
ln -s "$self" "$test_tmp/awk-failure/awk"

case_count=0
for test_case in clean alarm unknown invalid assertions warning external-warning external-error \
    incomplete status timeout version gcc-version missing missing-cc \
    missing-body spec-body byte-count coverage old-coverage old-assertions duplicate wrong-oracle awk-failure \
    missing-supervisor supervisor-error old-initialization-assertions old-helper-assertions \
    uppercase-warning uppercase-error mixed-warning mixed-error; do
    analyzer="$test_tmp/frama-aes-fixture"
    preprocessor="$test_tmp/gcc-aes-fixture"
    deadline="$test_tmp/timeout-aes-fixture"
    expected=1
    test_path=$PATH
    case "$test_case" in
        clean) expected=0 ;;
        status) expected=23 ;;
        timeout) expected=124 ;;
        missing) analyzer="$test_tmp/no-analyzer"; expected=127 ;;
        missing-cc) preprocessor="$test_tmp/no-preprocessor"; expected=127 ;;
        awk-failure) test_path="$test_tmp/awk-failure:$PATH" ;;
        missing-supervisor) deadline="$test_tmp/no-deadline"; expected=127 ;;
        supervisor-error) expected=24 ;;
    esac
    actual=0
    PATH="$test_path" FRAMA_C="$analyzer" FRAMA_CPP_CC="$preprocessor" \
        FRAMA_TIMEOUT="$deadline" FRAMA_AES_CASE="$test_case" \
        sh "$repo_root/tests/test_frama_aes_nist.sh" \
        >"$test_tmp/$test_case.log" 2>&1 || actual=$?
    if [ "$actual" -ne "$expected" ]; then
        cat "$test_tmp/$test_case.log" >&2
        printf 'FAIL: synthetic %s case returned %s, expected %s\n' \
            "$test_case" "$actual" "$expected" >&2
        exit 1
    fi
    pass_status=0
    grep -Fq 'PASS: Frama-C portable AES,' "$test_tmp/$test_case.log" || pass_status=$?
    if [ "$test_case" = clean ]; then
        [ "$pass_status" -eq 0 ]
    elif [ "$pass_status" -ne 1 ]; then
        printf 'FAIL: synthetic %s failure printed success or the result check failed\n' "$test_case" >&2
        exit 1
    fi
    printf 'PASS: synthetic AES formal-gate %s case\n' "$test_case"
    case_count=$((case_count + 1))
done
printf 'PASS: %s diagnostic/status controls; this does not run or prove AES\n' "$case_count"
