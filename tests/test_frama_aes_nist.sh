# Fixed NIST SP 800-38A F.1.5 vectors through the portable C implementation.
# This is not a proof for arbitrary keys, modes, inputs or assembly dispatch.
set -eu
export LC_ALL=C
repo_root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd -P)
frama_c=${FRAMA_C:-frama-c}
cpp_cc=${FRAMA_CPP_CC:-gcc}
deadline=${FRAMA_TIMEOUT:-timeout}
# Handle failed substitutions explicitly: older /bin/sh implementations may
# replace their status when errexit terminates an assignment.
version=$("$frama_c" -version) || exit "$?"
case "$version" in
    '29.0'*) ;;
    *) printf 'ERROR: this Eva result gate requires Frama-C 29.0, got %s\n' "$version" >&2; exit 1 ;;
esac
version=$("$cpp_cc" -dumpfullversion) || exit "$?"
case "$version" in
    '14.3.0') ;;
    *) printf 'ERROR: this Eva preprocessing profile requires GCC 14.3.0, got %s\n' "$version" >&2; exit 1 ;;
esac
if ! command -v "$deadline" >/dev/null; then
    printf 'ERROR: GNU-compatible deadline tool not found: %s\n' "$deadline" >&2
    exit 127
fi
if ! command -v awk >/dev/null; then
    printf 'ERROR: awk not found\n' >&2
    exit 127
fi
log=$(mktemp "${TMPDIR:-/tmp}/zupt-frama-aes.XXXXXXXX")
trap 'rm -f -- "$log"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

# Keep the machine model and preprocessing consistent with the reviewed run.
# GCC's wrapped toolchain linker need not be changed: this analysis emits no binary.
cpp_args="-I\"$repo_root/include\" -UNDEBUG"
if "$deadline" -s TERM -k 5 120 "$frama_c" -machdep gcc_x86_64 \
    -cpp-command="\"$cpp_cc\" -C -E -I." -cpp-frama-c-compliant \
    -cpp-extra-args="$cpp_args" \
    -eva -eva-slevel 4096 -eva-plevel 512 -eva-no-builtins-auto \
    -eva-show-progress -main main \
    "$repo_root/src/zupt_aes256.c" "$repo_root/tests/test_aes_nist.c" \
    >"$log" 2>&1; then
    cat "$log"
else
    status=$?
    cat "$log"
    exit "$status"
fi

# Frama-C can return zero with invalid assert preconditions and a pruned main.
# Version-pinned output checks deliberately fail closed if the schema changes.
# Eva counts four initialization-loop properties, two key-initialization
# assertions, one gmul loop invariant and fourteen block-loop invariants,
# not the 64 byte comparisons.
# Those comparisons use __FC_assert's nonnull_c precondition.
if ! awk '
    tolower($0) ~ /(^|[[:space:]])(warning:|error:)/ { bad = 1 }
    /got status (unknown|invalid)/ { bad = 1 }
    /NON TERMINATING FUNCTION/ { bad = 1 }
    /^\[eva\] using specification for function / {
        if ($NF != "__FC_assert") bad = 1
    }
    /^\[eva\] computing for function zupt_aes256_init <- main\.$/ { init++ }
    /^\[eva\] computing for function zupt_aes256_encrypt_block <- main\.$/ { encrypt++ }
    /^\[eva\] computing for function gmul <- zupt_aes256_encrypt_block <- main\.$/ { multiply++ }
    /^\[eva\] computing for function xtime <- gmul <- zupt_aes256_encrypt_block <- main\.$/ { xtime++ }
    /^\[eva\] computing for function __FC_assert <- main\.$/ { bytes++ }
    /function __FC_assert: precondition '\''nonnull_c'\'' got status valid\./ { oracle++ }
    /^\[eva:final-states\] Values at end of function main:$/ { in_main = 1; main++ }
    in_main && /^[[:space:]]*__retres ∈ \{0\}$/ { returned++ }
    /^\[eva:summary\] ====== ANALYSIS SUMMARY ======$/ { in_main = 0; summary++ }
    /^[[:space:]]*[0-9]+ alarms generated by the analysis\.$/ { alarm_rows++ }
    /^[[:space:]]*Assertions[[:space:]]/ { assertion_rows++ }
    /^[[:space:]]*Preconditions[[:space:]]/ { precondition_rows++ }
    /^[[:space:]]*No errors or warnings raised during the analysis\.$/ { clean++ }
    /^[[:space:]]*0 alarms generated by the analysis\.$/ { alarms++ }
    /^[[:space:]]*Assertions[[:space:]]+21 valid[[:space:]]+0 unknown[[:space:]]+0 invalid[[:space:]]+21 total$/ { assertions++ }
    /^[[:space:]]*Preconditions[[:space:]]+7 valid[[:space:]]+0 unknown[[:space:]]+0 invalid[[:space:]]+7 total$/ { preconditions++ }
    /^[[:space:]]*In these functions, 162 statements reached \(out of 162\): 100% coverage\.$/ { statements++ }
    /^[[:space:]]*100% of the logical properties reached have been proven\.$/ { proven++ }
    END {
        if (bad || !init || !encrypt || !multiply || !xtime || bytes != 64 ||
            oracle != 1 || main != 1 || returned != 1 || summary != 1 ||
            clean != 1 || alarms != 1 || assertions != 1 || preconditions != 1 ||
            alarm_rows != 1 || assertion_rows != 1 || precondition_rows != 1 ||
            statements != 1 || proven != 1) exit 1
    }
' "$log"; then
    printf 'FAIL: AES fixture analysis has diagnostics, incomplete coverage or unproved properties\n' >&2
    exit 1
fi
printf 'PASS: Frama-C portable AES, four fixed NIST F.1.5 blocks, 64 byte checks (limited scope)\n'
